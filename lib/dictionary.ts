export const getTranslation = (lang: Language, keyPath: string): string => {
  const keys = keyPath.split('.');
  let current: any = translations[lang];
  for (const k of keys) {
    if (current && current[k] !== undefined) {
      current = current[k];
    } else {
      return keyPath;
    }
  }
  return typeof current === 'string' ? current : keyPath;
};
